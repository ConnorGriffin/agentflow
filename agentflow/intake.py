"""Intake — the autonomous front of the pipe (ADR 0016).

Every open issue with no state label passes through here before it can be built, except
`wayfinder:*` planning artifacts, which stay upstream until wayfinder files build tickets.
Intake *grounds* the request (reads the code, and pulls a read-only real-data snapshot
if the repo declares one), *rewrites* it into something specific, and *routes* it to
exactly one outcome:

- `ready-for-agent` — clear as day; intake writes the build brief and stamps the two
  dials (complexity + effort, ADR 0018) so the loop can build it.
- `agentflow:needs-grilling` — a real, outcome-changing fork it can't settle from
  code/data, or a request that contradicts a recorded ADR; it posts questions in the
  *maintainer's* voice and holds (ADR 0019).
- `agentflow:needs-mockup` — a user-facing surface beyond a minor bugfix; holds for a
  `/ui-craft lock` pass.

Same shape as the reviewer: a tool-agnostic session does the grounding and emits a
decision that matches the provider-neutral `INTAKE_RESULT_SCHEMA`, enforced natively by
each CLI (Claude `--json-schema`, Codex `--output-schema`); `parse_intake` validates that
structured object into an `IntakeResult`. Parsing is **fail-safe** — anything we can't
read as a confident `ready`/`mockup` falls back to holding for a human (`grill`), never an
accidental build, and a `ready` whose complexity is missing/invalid is an explicit invalid
result rather than a silent upgrade to the deep tier.

The session coordinator owns launch. This module keeps Intake's prompt, parser, routes, and
idempotent GitHub projection; `parse_intake` and `intake_labels` are pure test surfaces.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from enum import Enum

from agentflow import github
from agentflow.runner import Complexity, Effort, MockupScope
from agentflow.shell_crib import SHELL_CRIB

# The provider-neutral shape Intake's terminal decision must match. Each runner adapter
# translates it into that CLI's native structured-output surface; the CLI enforces it, so
# the parser validates a real object rather than scavenging JSON out of free text. Optional
# dials are nullable so a hold route (grill/mockup/nothing-new) omits them while still
# satisfying providers that require every property (OpenAI-style strict schemas).
INTAKE_RESULT_SCHEMA = {
    "type": "object",
    "additionalProperties": False,
    "properties": {
        "route": {"type": "string", "enum": ["ready", "grill", "mockup", "nothing-new"]},
        "title": {"type": "string"},
        "body": {"type": "string"},
        "complexity": {"type": ["string", "null"], "enum": ["standard", "deep", None]},
        "effort": {"type": ["string", "null"],
                   "enum": ["low", "medium", "high", "extra", None]},
        "mockup_scope": {"type": ["string", "null"],
                         "enum": ["local", "surface", None]},
    },
    "required": ["route", "title", "body", "complexity", "effort", "mockup_scope"],
}

_DISCLAIMER = "> *agentflow intake — generated by AI.*"
INTAKE_MARK = "agentflow intake"  # substring that identifies an intake comment we posted

# Invisible fence (renders as nothing) marking where the brief ends and the preserved
# as-filed text begins. Lets a re-intake swap the brief in place instead of stacking a
# second one — everything from this marker down is the untouched original.
_ORIGINAL_MARK = "<!-- agentflow:original-below -->"

# The thread reply on a ready routing: a short, conversational note — not the brief
# itself. The brief is a build input and lives in the description now; this comment is
# the human-facing "here's what I did" and carries the intake marker so resume still
# keys off it.
_READY_COMMENT = (
    f"{_DISCLAIMER}\n\n"
    "Grounded and scoped this — the full Agent Brief is in the description now, so the "
    "build and review read straight from it. Your issue as filed is preserved under a "
    "collapsed block at the bottom. Take a look, and reply here if any of the scope is off."
)


class IntakeRoute(str, Enum):
    READY = "ready"     # build-ready — write the brief, stamp dials, proceed
    GRILL = "grill"     # hold: a real fork only the human can settle
    MOCKUP = "mockup"   # hold: needs a locked visual spec first
    NOTHING_NEW = "nothing-new"  # resume found nothing genuinely open changed — stay quiet


@dataclass(frozen=True, slots=True)
class IntakeResult:
    route: IntakeRoute
    body: str                        # the brief / questions / mockup kickoff to post
    title: str = ""                  # rewritten title ("" = leave as filed)
    complexity: Complexity | None = None
    effort: Effort | None = None
    mockup_scope: MockupScope | None = None  # local|surface — only on a mockup route
    parsed: bool = True
    detail: str = ""
    infra_failed: bool = False       # a worktree/provision/launch failure, not a model decision
    hardening: str = ""              # what the attack rounds did to this brief before it was
                                     # published (ADR 380) — appended to the ready comment, so it
                                     # is part of the comment the durability proof matches


def _held(detail: str) -> IntakeResult:
    """Fail-safe: an intake we can't read as confident-ready holds for the human."""
    body = (f"{_DISCLAIMER}\n\nI couldn't ground this into a confident scope on my own. "
            "Let's settle it together — reply here with what you meant, or run "
            "`/agentflow pickup` to drive it live.")
    return IntakeResult(IntakeRoute.GRILL, body, parsed=False, detail=detail)


def held_build_result(status: str, where: str) -> IntakeResult:
    """The hold a stuck build hands back — routes the issue to `needs-grilling` instead of
    leaving it `ready-for-agent`, where the loop would re-pick it every cycle: a fresh build
    session, a duplicate bail comment, and a duplicate ping per cycle, with the rest of the
    queue stalled behind it (ADR 0021's claim only covers a *live* build). The body carries
    the intake marker, so a maintainer reply resumes it through the normal re-intake path
    (ADR 0019). Pure (test surface)."""
    body = (f"{_DISCLAIMER}\n\nThe build stopped before opening a PR ({status}) — details in "
            f"{where}. I've held this rather than retrying blind. Reply here with what's "
            "missing (or run `/agentflow pickup` to drive it live) and I'll re-scope and retry.")
    return IntakeResult(IntakeRoute.GRILL, body)


_NEVER_READ = "I never got to read this issue — the coding agent's provider "
_RETRY = ("reply here and I'll pick this up again, or run `/agentflow pickup` to drive it "
          "live.")

# The diagnosis + remediation for each kind of permanent provider condition (issue #342). One
# fixed body per reason: an access refusal is the only one a re-authenticate helps, a rejected
# request means the sign-in is fine, a spend ceiling is a budget the run hit, and anything we
# couldn't type says only what we know. Keyed by the typed reason the provider observation
# preserved, so a restart composes the same body and the handoff still posts exactly once.
_PROVIDER_FAILURE_COPY = {
    "access": ("refused the session outright (an expired sign-in, a billing or plan limit, or "
               "a permission problem). So there's no question waiting on you here and no "
               "product decision pending.\n\nRe-authenticate the coding agent — or check its "
               f"billing, plan, and permissions — then {_RETRY}"),
    "rejected-request": ("rejected the request itself — too large for the model, an "
                         "unrecognized model, or a request it wouldn't accept. The coding "
                         "agent's credentials are fine, and there's no product decision "
                         "pending here either.\n\nThis one needs a look at what the coding "
                         f"agent was asked to send; once that's sorted, {_RETRY}"),
    "spend": ("stopped the run at its configured spending cap before the model read anything. "
              "The coding agent's credentials are fine, and there's no product decision "
              f"pending here.\n\nRaise or reset the cap for this work, then {_RETRY}"),
    "unspecified": ("ended the session permanently, without telling us which condition it was. "
                    "So there's no question waiting on you here and no product decision "
                    "pending.\n\nThis one needs a look at the coding agent's health before it "
                    f"can run again; once it's back, {_RETRY}"),
}

# The one condition that is not the provider's at all: the machine could not carry a session, so
# the agent never got a working command line and never reached this issue (issue #386). It needs
# its own whole body rather than a tail on ``_NEVER_READ`` — nothing here is the coding agent's
# provider refusing anything, and the remedy is on the machine rather than in the issue. Fixed
# text like the others, so a restarted daemon recomposes it byte-identically.
_ENVIRONMENT_FAILURE = (
    "I never got as far as reading this issue — the machine that runs the coding agent couldn't "
    "give it a working command line, so the session stopped before it could look at anything. "
    "Nothing here is waiting on a decision from you, the issue itself is fine, and no amount of "
    "retrying would have helped.\n\nThis is almost always too many leftover session checkouts "
    "piling up in the repository: past a point, the safety rules the coding agent passes to "
    "every command grow larger than the operating system will accept, and every session in that "
    f"repository dies on its first command. Reclaim those leftover checkouts, then {_RETRY}")


def _provider_failed(detail: str, reason: str = "unspecified") -> IntakeResult:
    """A *permanent* condition stopped the session before the model ever read the issue (issue
    #328). There is no product decision waiting, so the handoff names the failure and its
    remediation instead of asking the human to settle a scope question that was never asked.
    ``reason`` says *which* condition it was, so a rejected request or a spend ceiling isn't
    misdiagnosed as an expired sign-in (issue #342), and an environment that couldn't carry a
    session at all names the machine rather than blaming the coding agent's provider (issue
    #386); an unknown reason falls back to the neutral body that prescribes no wrong remedy. The
    route stays ``GRILL`` so the held state label and the durable-handoff marker machinery are
    unchanged; each body is fixed text for its reason so a restarted daemon re-detects the same
    marker."""
    if reason == "environment":
        body = _ENVIRONMENT_FAILURE
    else:
        body = _NEVER_READ + _PROVIDER_FAILURE_COPY.get(
            reason, _PROVIDER_FAILURE_COPY["unspecified"])
    return IntakeResult(IntakeRoute.GRILL, f"{_DISCLAIMER}\n\n{body}",
                        parsed=False, detail=detail, infra_failed=True)


def _infra_failed(detail: str) -> IntakeResult:
    """An *infrastructure* failure — the worktree, provision, or launch fell over before
    the model ever weighed in. Unlike a model-level hold this is not the issue's fault, so
    the loop retries it silently next cycle rather than spending the issue's state on a
    spammy hold (ADR 0019 — no spam). The body is only ever posted if the loop's bounded
    backstop fires after a run of consecutive failures."""
    body = (f"{_DISCLAIMER}\n\nI keep hitting a setup problem before I can even start "
            "grounding this — it's on my end, not your issue. I'll keep retrying; flagging "
            "it here in case it needs a look.")
    return IntakeResult(IntakeRoute.GRILL, body, parsed=False, detail=detail, infra_failed=True)


def _enum_or_none(enum, raw):
    try:
        return enum(str(raw).strip().lower())
    except ValueError:
        return None


def parse_intake(payload: str) -> IntakeResult:
    """Validate a grounding session's structured decision. Pure, fail-safe (test surface).

    The CLI enforces `INTAKE_RESULT_SCHEMA` natively, so the payload is the decision object
    itself — parsed strictly, never scavenged out of reasoning prose. A confident `ready`
    needs a valid route, a non-empty body, and a valid complexity: a missing/invalid
    complexity is an explicit invalid result, never a silent upgrade to the deep tier
    (effort still softens to `medium`, since it only guides work, not model size). Anything
    unreadable → held for a human. Never raises.
    """
    try:
        data = json.loads(payload.strip() or "null")
        if not isinstance(data, dict):
            return _held("intake output was not a structured decision object")
        route = _enum_or_none(IntakeRoute, data.get("route"))
        if route is None:
            return _held("intake decision carried no valid route")
        if route is IntakeRoute.NOTHING_NEW:
            return IntakeResult(route, "")  # a no-op resume: no body, nothing to post
        body = str(data.get("body", "")).strip()
        if not body:
            return _held("intake decision carried no body")
        title = str(data.get("title", "")).strip()
        if route is IntakeRoute.READY:
            complexity = _enum_or_none(Complexity, data.get("complexity"))
            if complexity is None:
                return _held("ready intake carried no valid complexity")
            effort = _enum_or_none(Effort, data.get("effort")) or Effort.MEDIUM
            return IntakeResult(route, body, title, complexity, effort)
        if route is IntakeRoute.MOCKUP:
            # Scope is fail-safe to `local` per ADR 0048: an unknown/missing/invalid value
            # never reopens the whole visual world, only the narrower addition.
            scope = _enum_or_none(MockupScope, data.get("mockup_scope")) or MockupScope.LOCAL
            return IntakeResult(route, body, title, mockup_scope=scope)
        return IntakeResult(route, body, title)
    except Exception as e:  # noqa: BLE001 — fail-safe, never propagate
        return _held(f"parse error: {type(e).__name__}")


def compose_ready_body(brief: str, current_body: str) -> str:
    """The issue body after a ready routing: the Agent Brief on top, the as-filed text
    preserved verbatim under a collapsed `<details>` at the bottom (ADR 0016/0022 — the
    brief must live where builder and reviewer read it). Pure (test surface).

    Idempotent on re-intake: if `current_body` already carries a composed brief (the
    `_ORIGINAL_MARK` fence), the previously-preserved original is kept exactly as-is and
    only the brief above it is replaced — never a second `<details>`, never the old brief
    nested inside the new one."""
    brief = brief.strip()
    idx = current_body.find(_ORIGINAL_MARK)
    if idx != -1:
        return f"{brief}\n\n{current_body[idx:].strip()}"
    original = current_body.strip() or "_(no description as filed)_"
    return (f"{brief}\n\n{_ORIGINAL_MARK}\n<details>\n<summary>Original issue as filed</summary>"
            f"\n\n{original}\n\n</details>")


def _ready_body_has_envelope(body: str) -> bool:
    """Whether ``body`` has one complete generated original-text envelope."""
    index = body.find(_ORIGINAL_MARK)
    if index <= 0 or body.count(_ORIGINAL_MARK) != 1:
        return False
    tail = body[index:]
    opening = (f"{_ORIGINAL_MARK}\n<details>\n"
               "<summary>Original issue as filed</summary>\n\n")
    return tail.startswith(opening) and tail.endswith("\n\n</details>")


def _ready_body_is_canonical(body: str, brief: str) -> bool:
    """Whether the exact requested brief precedes one complete original-text envelope."""
    return (body.startswith(f"{brief.strip()}\n\n{_ORIGINAL_MARK}")
            and _ready_body_has_envelope(body))


def intake_labels(result: IntakeResult) -> list[str]:
    """The labels to stamp for a routed issue — exactly one state, plus dials when
    ready. Pure (test surface)."""
    if result.route is IntakeRoute.READY:
        return ["ready-for-agent",
                f"agentflow:complexity:{result.complexity.value}",
                f"agentflow:effort:{result.effort.value}"]
    if result.route is IntakeRoute.MOCKUP:
        scope = result.mockup_scope or MockupScope.LOCAL
        return ["agentflow:needs-mockup", f"agentflow:mockup:{scope.value}"]
    return ["agentflow:needs-grilling"]


_DOUBLE_QUOTED_RE = re.compile(r"^>\s*>", re.MULTILINE)


def _strip_quoted_lines(body: str) -> str:
    """Remove re-quoted lines (starting with '> >') so a GitHub quote-reply of our
    comment doesn't mask our marker. Our marker lives on a single-'>' line in our
    posts — those are kept so we can still detect our own comments."""
    return "\n".join(
        line for line in body.splitlines() if not _DOUBLE_QUOTED_RE.match(line)
    )


def awaiting_recheck(comments: list[dict], allowlist: set[str] | None = None) -> bool:
    """True when a held issue's most recent non-empty comment from an allowlisted author
    is the maintainer's reply — i.e. they answered and it's our move again (ADR 0019).
    False when the last word is ours, or there are no qualifying comments. Pure.

    Quote-reply lines (starting with '>') are stripped before scanning so a maintainer
    who quotes our comment still counts as a reply, not as us. Comments from authors not
    in *allowlist* are skipped entirely; *allowlist=None* disables the author filter."""
    for c in reversed(comments):
        body = c.get("body", "").strip()
        if not body:
            continue
        if allowlist is not None and c.get("author", {}).get("login", "") not in allowlist:
            continue
        return INTAKE_MARK not in _strip_quoted_lines(body)
    return False


def replies_since_intake(comments: list[dict], allowlist: set[str] | None = None) -> str:
    """The maintainer's comment(s) after our last intake comment — their answer text.
    Pure (test surface).

    Quote-reply lines are stripped before scanning for the cut point so a maintainer
    quote-reply is not mistaken for our marker. Only comments from *allowlist* authors
    are collected; *allowlist=None* collects all (backwards-compatible)."""
    tail = []
    for c in reversed(comments):
        if INTAKE_MARK in _strip_quoted_lines(c.get("body", "")):
            break
        if allowlist is not None and c.get("author", {}).get("login", "") not in allowlist:
            continue
        tail.append(c.get("body", "").strip())
    return "\n\n".join(b for b in reversed(tail) if b)


