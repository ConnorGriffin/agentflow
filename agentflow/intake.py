def intake_prompt(repo: str, issue: dict, extra: str = "", comments: str = "") -> str:
    """The durable provider input for one Intake stage.

    ``comments`` are maintainer comments the issue picked up after it was filed, on a *fresh*
    intake. An issue is often narrowed, redirected, or half-deferred in its own thread minutes
    after it is written, and reading only the body produced a confident brief for work its owner
    had already shelved. ``extra`` is the resume channel — the maintainer's answer to an earlier
    hold — and carries its own framing; the caller supplies one or the other, never both, so this
    stays one rule per input: append each section if it has anything in it.
    """
    from agentflow.intake_attachments import ATTACHMENTS_DIRNAME, extract_image_urls
    body = issue.get("body") or ""
    prompt = _fill(INTAKE_PROMPT, repo=repo, n=str(issue["number"]), disclaimer=_DISCLAIMER,
                   title=issue.get("title", ""), body=body or "(no description)")
    if extract_image_urls(body):
        prompt += _IMAGE_HANDOFF.replace("{dir}", ATTACHMENTS_DIRNAME)
    if comments:
        prompt += _OWNER_COMMENTS.replace("{comments}", comments)
    if extra:
        prompt += ("\n\nTHE MAINTAINER HAS REPLIED to your earlier hold — treat this as their "
                   "answer or waiver: promote to ready if the issue is now settled (they answered "
                   "your questions, waived the visual spec requirement, or pointed at a locked spec), "
                   "else re-post ONLY what's still open. "
                   "IF this issue was held for a MOCKUP and a variant round was already drawn (a "
                   "comment on the issue naming variants A/B/C/D with screenshots), the reply may be "
                   "a PICK — \"B\", \"the second one\", \"A but tighter\". In that case: read that "
                   "mockup comment (it links the committed variant files on a mockup branch and "
                   "carries each variant's `LOCKED` contract inline), map the pick to its variant, "
                   "and route \"ready\" with a brief that (a) records the EXACT committed mockup path "
                   "and branch for the chosen variant, and (b) copies that variant's `LOCKED` contract "
                   "VERBATIM into the brief under a `## LOCKED visual contract` heading — word for word, "
                   "no paraphrase or trimming — so review stays self-contained after the mockups are "
                   "archived (ADR 0018/0048 — the build's screenshots are judged against this contract, "
                   "not just the committed file). A request for a DIFFERENT or fresh set is NOT a pick — "
                   "re-hold (route \"mockup\") as a follow-up; never auto-loop a new variant round. "
                   'If nothing genuinely open changed — the reply was chit-chat, or it didn\'t move '
                   'any open question — answer route "nothing-new" (no body) and I\'ll stay quiet '
                   "rather than restate myself.\n"
                   f"---\n{extra}\n---")
    return prompt


_REDRAFT = """

YOUR DRAFT WAS ATTACKED. Nothing has been published — the issue is untouched and the maintainer
has seen none of this. You drafted the plan below, a cold session with no memory of your reasoning
tried to break it, and these are its objections. This is round {round} of at most {max_rounds};
answer them and hand back your best plan.

Your draft:
Title: {draft_title}
---
{draft_body}
---

Its objections:
---
{objections}
---

HOW TO ANSWER:
- Where an objection lands, FIX THE PLAN. Re-ground it against the code first — the attacker may
  be wrong about the code too, and adopting a wrong correction is worse than the original claim.
- Where an objection does not land, keep your plan and say why in one line under a
  `## Answered objections` heading at the end of the brief. Standing your ground on evidence is a
  correct answer; folding to every objection is not.
- If the objections expose a genuine fork that only the maintainer can settle — a real choice that
  CHANGES THE RESULT and no amount of reading the code decides — route "grill" and ask them. That
  is not a failure; it is the one thing this whole exercise is for. Do not grill over something you
  can decide.

Answer with a complete decision, exactly as before: the whole brief again, not a diff against your
last one. Your route may change; the dials may change."""


def redraft_prompt(base_prompt: str, draft_title: str, draft_body: str,
                   objections: str, *, round: int, max_rounds: int) -> str:
    """The durable provider input for one hardening round of intake (ADR 380). Pure.

    ``base_prompt`` is the grounding prompt the *first* draft came from, carried unchanged down
    the chain — so every redraft re-grounds from the same issue snapshot the argument started
    from, and a round replayed after a crash composes byte-identical input. It is deliberately
    the whole prompt rather than a follow-up message: this is a new session, so it has to be
    able to re-ground from nothing.
    """
    return base_prompt + _fill(
        _REDRAFT, round=str(round), max_rounds=str(max_rounds),
        draft_title=draft_title,
        draft_body=draft_body.strip() or "(no draft body)",
        objections=objections.strip() or "(no objections recorded)")


def _ensure_label(repo: str, name: str) -> None:
    """Idempotently create the label so `--add-label` can't fail on a fresh repo."""
    color = _LABEL_COLORS.get(name, "ededed")
    github.create_label(repo, name, color)


def _result_comment(result: IntakeResult) -> str:
    """The stable comment payload for one route, excluding an optional retitle preface.

    A published brief carries one extra line saying what the attack rounds did to it before it
    was posted (ADR 380). It is part of the stable payload rather than a second comment, so the
    idempotence and durability proofs keep matching exactly one comment per route.
    """
    if result.route is not IntakeRoute.READY:
        return result.body
    return f"{_READY_COMMENT}\n\n{result.hardening}" if result.hardening else _READY_COMMENT


def _comment_matches_result(body: str, result: IntakeResult) -> bool:
    """Whether a durable issue comment is this route's output.

    The first projection may include the old title as a conversational preface. A retry after
    the title mutation can no longer reconstruct that old title, so match the stable payload at
    the end while still requiring the generated retitle preface shape.
    """
    actual = body.strip()
    expected = _result_comment(result).strip()
    return actual == expected or (
        actual.startswith('> Retitled from: "') and actual.endswith(f"\n\n{expected}"))


def _result_comment_exists(repo: str, issue_number: int,
                           result: IntakeResult) -> bool | None:
    """Whether this route's comment exists, or ``None`` when GitHub is unreadable.

    Unreadable is deliberately distinct from absent: treating uncertainty as absence could
    post a duplicate while replaying a partially projected route.
    """
    comments = github.issue_comments(repo, issue_number)
    if comments is None:
        return None
    return any(_comment_matches_result(c.body, result) for c in comments)


def apply_intake(repo: str, issue_number: int, current_title: str,
                 current_labels: list[str], result: IntakeResult,
                 source_title: str | None = None,
                 source_body: str | None = None) -> str:
    """Write the decision to GitHub, then set the one state label + dials (clearing any
    other state label). Impure; returns a one-line summary.

    On `ready` the brief is a **build input**: it goes into the issue *body* (where the
    builder prompt and reviewer acceptance read it, ADR 0016/0022), the as-filed text is
    preserved below it, and the thread gets a short conversational note. On `grill` /
    `mockup` — those are conversations, not build inputs — the full text stays a comment.

    No-spam (ADR 0019): a `nothing-new` resume writes nothing at all, and an apply whose
    comment materially matches the latest comment we already posted is skipped — a
    nothing-changed recheck must not restate itself."""
    if result.route is IntakeRoute.NOTHING_NEW:
        return "nothing new — nothing to post"

    labels = intake_labels(result)
    target_title = result.title or source_title or ""
    retitled_from = current_title if (target_title and target_title != current_title) else None
    comment = _result_comment(result)
    if retitled_from is not None:
        comment = f'> Retitled from: "{retitled_from}"\n\n{comment}'

    # Idempotent across partial writes: once this route's comment exists, retries finish any
    # remaining title/body/label mutations without posting it again.
    comment_done = _result_comment_exists(repo, issue_number, result)
    if comment_done is None:
        return f"routed -> {result.route.value} deferred (comments unreadable)"
    exact_labels = set(labels).issubset(current_labels)
    stale_state = any(name in current_labels and name not in set(labels) for name in STATE_LABELS)
    stale_dials = any(any(name.startswith(p) for p in _MANAGED_PREFIXES)
                      and name not in set(labels) for name in current_labels)
    title_done = not retitled_from
    if result.route is IntakeRoute.READY:
        current_body = github.issue_body(repo, issue_number)
        if current_body is None:
            # Fail closed: we cannot compose the brief without the original to preserve.
            return f"routed -> {result.route.value} deferred (body unreadable)"
        if (source_body is None and _ORIGINAL_MARK in current_body
                and not _ready_body_has_envelope(current_body)):
            return f"routed -> {result.route.value} deferred (body envelope malformed)"
        # Coordinated Intake projects from its immutable submission snapshot. Legacy callers
        # without that source retain the old idempotent behavior over the live body.
        body_source = source_body if source_body is not None else current_body
        expected_body = compose_ready_body(result.body, body_source)
        body_done = (current_body == expected_body
                     and _ready_body_is_canonical(current_body, result.body))
    else:
        current_body = ""
        body_done = True
    if (comment_done and exact_labels and not stale_state and not stale_dials
            and title_done and body_done):
        return f"unchanged -> {result.route.value} (already posted)"

    if retitled_from is not None:
        github.edit_title(repo, issue_number, target_title)
    if result.route is IntakeRoute.READY:
        github.edit_body(repo, issue_number, expected_body)
    if not comment_done:
        github.comment(repo, issue_number, comment)

    for name in labels:
        _ensure_label(repo, name)
    new_labels_set = set(labels)
    for name in labels:
        github.add_label(repo, issue_number, name)
    for name in STATE_LABELS:  # keep exactly one state label — clear stale holds on promote
        if name not in new_labels_set and name in current_labels:
            github.remove_label(repo, issue_number, name)
    for name in current_labels:  # clear stale dials/scope — a re-route leaves exactly one of each
        if any(name.startswith(p) for p in _MANAGED_PREFIXES) and name not in new_labels_set:
            github.remove_label(repo, issue_number, name)
    tail = "" if result.parsed else " (fail-safe hold)"
    return f"routed -> {result.route.value}{tail}"


def intake_result_is_durable(repo: str, issue_number: int, result: IntakeResult,
                             source_title: str | None = None,
                             source_body: str | None = None) -> bool:
    """Verify that the routing decision is visible on GitHub before disposal."""
    if result.route is IntakeRoute.NOTHING_NEW:
        return True
    # One whole-issue snapshot: a route is only visible if title, labels, comment and body agree
    # at the same moment, so a proof assembled from separate reads would be no proof.
    issue = github.issue_view(repo, issue_number)
    if issue is None:
        return False
    labels = issue.labels
    required = set(intake_labels(result))
    if not required.issubset(labels):
        return False
    if any(name in labels and name not in required for name in STATE_LABELS):
        return False
    if any(any(name.startswith(prefix) for prefix in _MANAGED_PREFIXES)
           and name not in required for name in labels):
        return False
    expected_title = result.title or source_title
    if expected_title is not None and issue.title != expected_title:
        return False
    if not any(_comment_matches_result(comment.body, result) for comment in issue.comments):
        return False
    if result.route is IntakeRoute.READY:
        # Prove the EXACT canonical composed body — the brief over the preserved original —
        # not just that the brief appears somewhere. `compose_ready_body` is idempotent on an
        # already-composed body, so the durable body must equal composing the brief over itself.
        body = issue.body
        if not _ready_body_is_canonical(body, result.body):
            return False
        if source_body is not None:
            return body == compose_ready_body(result.body, source_body)
        return True
    return True


def sweep_legacy_labels(repo: str) -> list[str]:
    """Migrate bare pre-enrollment needs-* labels to the agentflow:* vocabulary on open
    issues. Idempotent — safe to run more than once. Returns one-line change descriptions,
    one per issue touched."""
    issues = github.list_issues(repo, limit=500)
    if issues is None:
        return ["error: could not list issues"]
    changed = []
    for issue in issues:
        n = issue.number
        names = set(issue.labels)
        to_add: list[str] = []
        to_remove: list[str] = []
        for bare, namespaced in _LEGACY_LABEL_MAP.items():
            if bare in names:
                if namespaced not in names:
                    to_add.append(namespaced)
                to_remove.append(bare)
        if not to_remove:
            continue
        for name in to_add:
            _ensure_label(repo, name)
            github.add_label(repo, n, name)
        for name in to_remove:
            github.remove_label(repo, n, name)
        parts = []
        if to_add:
            parts.append(f"added {', '.join(sorted(to_add))}")
        parts.append(f"removed {', '.join(sorted(to_remove))}")
        changed.append(f"#{n}: {'; '.join(parts)}")
    return changed
